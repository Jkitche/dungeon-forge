// Settings ("genres"): the content tables, vocabulary, default art theme and layout
// tendencies for each kind of adventure location.

import type { ThemeKey } from "./renderer.ts";

export type GenreKey =
  "fantasy" | "scifi" | "steampunk" | "horror" | "wasteland";

/** Layout sliders a genre nudges when it is picked in the UI. */
export interface LayoutPreset {
  roundRoomChance: number;
  pillarChance: number;
  corridorStyle: "straight" | "winding";
  loopChance: number;
  doorChance: number;
  lockedDoorChance: number;
  secretDoorChance: number;
  windowChance: number;
  clutter: number;
}

export interface Genre {
  label: string;
  theme: ThemeKey;
  preset: LayoutPreset;
  /** Display labels for the monster and treasure entries in the room key. */
  encounterLabel: string;
  treasureLabel: string;
  /** "stairs", "lift", "ladder": used in "stairs up" / "lift down" tags. */
  stairWord: string;
  entranceName: string;
  exitName: string;
  entranceNote: string;
  exitNote: string;
  roomNames: readonly string[];
  caveNames: readonly string[];
  atmospheres: readonly string[];
  features: readonly string[];
  monsters: readonly string[];
  traps: readonly string[];
  specials: readonly string[];
  treasures: readonly string[];
}

